//! Vertical text, as MapLibre GL JS lays it out (util/script_detection.ts,
//! util/verticalize_punctuation.ts, shaping.ts isLineVertical).
//!
//! Characters with upright vertical orientation (CJK ideographs, kana,
//! Hangul, ...) stay upright along a vertical line: a label whose text has
//! any such character gets a vertical shaping too, used for point labels
//! with `text-writing-mode: vertical` and for line labels whenever their line
//! runs more vertically than horizontally on screen. Punctuation between such
//! characters becomes its vertical presentation form.
//!
//! The tables are generated from MapLibre's own functions
//! (unicode_properties.g.ts, `\p{sc=Arab}` and `\s` regular expressions,
//! verticalizedCharacterMap) evaluated over every code point.

fn in_ranges(table: &[(u32, u32)], cp: u32) -> bool {
    table.binary_search_by(|&(a, b)| if cp < a { std::cmp::Ordering::Greater } else if cp > b { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_ok()
}

/// codePointHasUprightVerticalOrientation.
pub fn upright(cp: u32) -> bool {
    in_ranges(&UPRIGHT, cp)
}

/// charHasRotatedVerticalOrientation.
fn rotated(cp: u32) -> bool {
    !(upright(cp) || in_ranges(&NEUTRAL, cp))
}

/// codePointAllowsIdeographicBreaking.
pub fn ideographic_breaking(cp: u32) -> bool {
    in_ranges(&IDEOGRAPHIC_BREAKING, cp)
}

/// allowsVerticalWritingMode: any character is upright.
pub fn allows_vertical_writing_mode(text: &str) -> bool {
    text.chars().any(|c| upright(c as u32))
}

/// The vertical presentation form of a punctuation character.
pub fn verticalized(c: char) -> Option<char> {
    VERTICAL_PUNCTUATION
        .binary_search_by_key(&(c as u32), |p| p.0)
        .ok()
        .and_then(|k| char::from_u32(VERTICAL_PUNCTUATION[k].1))
}

/// verticalizePunctuation: punctuation whose neighbours are not rotated
/// (or are punctuation themselves) takes its vertical form.
pub fn verticalize_punctuation(chars: &[char]) -> Vec<char> {
    let ok = |c: Option<&char>| c.is_none_or(|&c| !rotated(c as u32) || verticalized(c).is_some());
    (0..chars.len())
        .map(|i| {
            let prev = if i == 0 { None } else { chars.get(i - 1) };
            match verticalized(chars[i]) {
                Some(v) if ok(chars.get(i + 1)) && ok(prev) => v,
                _ => chars[i],
            }
        })
        .collect()
}

/// isLineVertical for a glyph of a vertical shaping: upright characters, or
/// with vertical point placement anything but whitespace and Arabic.
pub fn glyph_is_vertical(cp: u32, allow_vertical_placement: bool) -> bool {
    if allow_vertical_placement {
        !(in_ranges(&WHITESPACE, cp) || in_ranges(&ARABIC_SCRIPT, cp))
    } else {
        upright(cp)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn orientation_and_punctuation() {
        assert!(upright('東' as u32) && upright('の' as u32) && upright('한' as u32));
        assert!(!upright('A' as u32) && rotated('A' as u32));
        assert!(allows_vertical_writing_mode("Tokyo 東京") && !allows_vertical_writing_mode("Tokyo"));
        assert!(ideographic_breaking('京' as u32) && !ideographic_breaking('a' as u32));
        let v: String = verticalize_punctuation(&"東京(駅)".chars().collect::<Vec<_>>()).into_iter().collect();
        assert_eq!(v, "東京︵駅︶");
        // Next to a Latin letter, punctuation stays as it is.
        let v: String = verticalize_punctuation(&"A(B)".chars().collect::<Vec<_>>()).into_iter().collect();
        assert_eq!(v, "A(B)");
        assert!(glyph_is_vertical('A' as u32, true) && !glyph_is_vertical('A' as u32, false));
        assert!(!glyph_is_vertical(' ' as u32, true) && !glyph_is_vertical(0x0628, true));
    }
}

